"""T119: per-gamma specialists, dense rows, and a hard-constrained log-g output.

Modes
-----
hyper : T116 direct-E_conv model in the exact canonical (signed axis
        permutation + u -> -u) frame.  Baseline / specialists.
logg  : hard-constrained output in the same canonical frame:
            log g = log(|E_conv| / |E_point|),
            unit direction of E_conv expressed in the point-field frame,
        reconstruct E_conv = exp(log g) * |E_point| * Ehat, then map back.
        Far-field asymptote g -> 1 and Ehat -> Ehat_point is encoded exactly.

Data
----
pilot : ~/pr24/t112/pilot_all.npz (5400 configs, ~2 rows/config)
dense : generated by gen_dense.py (chosen configs x many rows).  Rows are
        subsampled to a fixed count for the "same volume" shape test.
"""
from __future__ import annotations

import argparse
import json
import os
import time

import numpy as np
import torch
import torch.nn as nn

TINY = 1e-30
PILOT = os.path.expanduser("~/pr24/t112/pilot_all.npz")

BINS = [(1.0, 1.5), (1.5, 3.0), (3.0, 10.0), (10.0, 30.0), (30.0, 100.001)]
BIN_NAMES = ["g1-1.5", "g1.5-3", "g3-10", "g10-30", "g30-100"]


# ---------------------------------------------------------------- geometry
def canon(cells, u, Rc):
    au = np.abs(u)
    aR = np.abs(Rc)
    p = np.lexsort((aR, au, cells), axis=1)
    Rcp = np.take_along_axis(Rc, p, axis=1)
    up = np.take_along_axis(u, p, axis=1)
    cellsn = np.take_along_axis(cells, p, axis=1)
    s = np.sign(Rcp)
    s[s == 0.0] = 1.0
    Rcn = s * Rcp
    un = s * up
    big = np.abs(un) > 1e-14
    first = np.argmax(big, axis=1)
    has = big.any(axis=1)
    t = np.ones(len(un))
    t[has] = np.sign(un[np.arange(len(un)), first])[has]
    t[t == 0] = 1.0
    un = un * t[:, None]
    return cellsn, un, Rcn, p, s, t


def inv_map(Yc, p, s):
    Y = np.empty_like(Yc)
    np.put_along_axis(Y, p, s * Yc, axis=1)
    return Y


def perp_basis(v):
    """Orthonormal (e1,e2) perpendicular to unit vectors v."""
    n = len(v)
    ref = np.zeros_like(v)
    idx = np.argmax(np.abs(v), axis=1)
    ref[np.arange(n), idx] = 1.0
    e1 = np.cross(ref, v)
    e1 /= np.maximum(np.linalg.norm(e1, axis=1), TINY)[:, None]
    e2 = np.cross(v, e1)
    return e1, e2


# ---------------------------------------------------------------- features
def features(d, mode):
    Rc = np.asarray(d["R_cells"], float)
    u = np.asarray(d["u"], float)
    cells = np.asarray(d["cells"], float)
    g = np.asarray(d["gamma"], float)
    Ep = np.asarray(d["E_point"], float)
    Ec = np.asarray(d["E_conv"], float)

    cellsn, un, Rcn, p, s, t = canon(cells, u, Rc)
    lg = np.log(g)
    bn = np.linalg.norm(un, axis=1)
    bh = un / np.maximum(bn, TINY)[:, None]
    r = np.linalg.norm(Rcn, axis=1)
    rp = np.einsum("ij,ij->i", Rcn, bh)
    rr = np.sqrt(np.maximum(r * r - rp * rp, 0.0))
    W = np.prod(np.clip(1.5 - np.abs(Rcn), 0.0, None), axis=1)
    dface = 1.5 - np.max(np.abs(Rcn), axis=1)
    Ec_c = s * np.take_along_axis(Ec, p, axis=1)
    Ep_c = s * np.take_along_axis(Ep, p, axis=1)
    base = [Rcn[:, 0], Rcn[:, 1], Rcn[:, 2],
            np.log(cellsn[:, 0]), np.log(cellsn[:, 1]), np.log(cellsn[:, 2]),
            lg, un[:, 0], un[:, 1], un[:, 2], bh[:, 0], bh[:, 1], bh[:, 2],
            r, rp, rr, W, dface,
            Ep_c[:, 0], Ep_c[:, 1], Ep_c[:, 2],
            np.log(np.maximum(np.linalg.norm(Ep_c, axis=1), TINY))]

    if mode == "hyper":
        X = np.stack(base, axis=1)
        meta = {"mode": "hyper", "p": p, "s": s, "Y": Ec_c, "Ec_c": Ec_c}
    elif mode == "logg":
        a = np.maximum(np.linalg.norm(Ep_c, axis=1), TINY)
        b = np.maximum(np.linalg.norm(Ec_c, axis=1), TINY)
        logg = np.log(b / a)
        Ehat_p = Ep_c / a[:, None]
        Ehat_c = Ec_c / b[:, None]
        e1, e2 = perp_basis(Ehat_p)
        t1 = np.einsum("ij,ij->i", Ehat_c, e1)
        t2 = np.einsum("ij,ij->i", Ehat_c, e2)
        t3 = np.einsum("ij,ij->i", Ehat_c, Ehat_p)
        X = np.stack(base, axis=1)
        meta = {"mode": "logg", "p": p, "s": s,
                "Y": np.stack([logg, t1, t2, t3], axis=1),
                "a": a, "Ehat_p": Ehat_p, "e1": e1, "e2": e2, "Ec_c": Ec_c}
    else:
        raise ValueError(mode)
    return X.astype(np.float32), meta


def reconstruct(model_out, meta, muY, sdY):
    Y = model_out * sdY + muY
    if meta["mode"] == "hyper":
        Ec_c = Y
    else:
        logg, t1, t2, t3 = Y[:, 0], Y[:, 1], Y[:, 2], Y[:, 3]
        D = np.stack([t1, t2, t3], axis=1)
        D = D / np.maximum(np.linalg.norm(D, axis=1), TINY)[:, None]
        # direction in the point-field frame
        Ehat = (D[:, 0:1] * meta["e1"] + D[:, 1:2] * meta["e2"]
                + D[:, 2:3] * meta["Ehat_p"])
        mag = np.exp(np.clip(logg, -30.0, 30.0)) * meta["a"]
        Ec_c = mag[:, None] * Ehat
    return inv_map(Ec_c, meta["p"], meta["s"])


def beta_of(d, sel):
    u = np.asarray(d["u"], float)[sel]
    return u / np.sqrt(1.0 + np.einsum("ij,ij->i", u, u))[:, None]


def rel_matrix(pred_E, d, sel):
    b = beta_of(d, sel)
    Ec = np.asarray(d["E_conv"], float)[sel]
    Bc = np.asarray(d["cB_conv"], float)[sel]
    pB = np.cross(b, pred_E)
    return np.abs(np.concatenate([pred_E - Ec, pB - Bc], axis=1)) / (
        1.0 + np.abs(np.concatenate([Ec, Bc], axis=1)))


def metrics(pred_E, d, sel):
    rel = rel_matrix(pred_E, d, sel)
    return {"n": int(len(rel)),
            "worst": float(rel.max()),
            "p99": float(np.quantile(rel, 0.99)),
            "median": float(np.median(rel))}


def strat(pred_E, d, sel):
    rel = rel_matrix(pred_E, d, sel)
    rowmax = rel.max(axis=1)
    g = np.asarray(d["gamma"], float)[sel]
    out = {}
    for gg in np.unique(g):
        m = g == gg
        out[f"gamma{gg:g}"] = {"n": int(m.sum()),
                               "worst": float(rel[m].max()),
                               "p99": float(np.quantile(rel[m], 0.99))}
    for (lo, hi), nm in zip(BINS, BIN_NAMES):
        m = (g >= lo) & (g < hi)
        if m.any():
            out[nm] = {"n": int(m.sum()), "worst": float(rel[m].max()),
                       "p99": float(np.quantile(rel[m], 0.99))}
    return out


def mlp(nin, width, depth, out):
    layers, n = [], nin
    for _ in range(depth):
        layers += [nn.Linear(n, width), nn.SiLU()]
        n = width
    layers.append(nn.Linear(n, out))
    return nn.Sequential(*layers)


# ---------------------------------------------------------------- data
def load_data(args):
    if args.data == "pilot":
        d = dict(np.load(PILOT, allow_pickle=True))
        return d
    parts = []
    for sp in ("train", "val", "test"):
        parts.append(dict(np.load(os.path.join(args.dense_dir, f"{sp}.npz"),
                                  allow_pickle=True)))
    d = {}
    for k in parts[0]:
        d[k] = np.concatenate([p[k] for p in parts], axis=0)
    if args.dense_rows and args.dense_rows > 0:
        tr = d["split"] == "train"
        keep = tr & (d["row"] < args.dense_rows)
        idx = np.where(keep | ~tr)[0]
        d = {k: v[idx] for k, v in d.items()}
    return d


class Net:
    def __init__(self, mode, X, meta, trf, args, dev):
        Y = meta["Y"]
        self.mode = mode
        self.meta = meta
        self.muX = X[trf].mean(0)
        sd = X[trf].std(0)
        sd[sd < 1e-12] = 1.0
        self.sdX = sd
        self.muY = Y[trf].mean(0)
        sy = Y[trf].std(0)
        sy[sy < 1e-12] = 1.0
        self.sdY = sy
        self.Xt = torch.from_numpy(((X - self.muX) / self.sdX).astype(np.float32)).to(dev)
        self.Yt = torch.from_numpy(((Y - self.muY) / self.sdY).astype(np.float32)).to(dev)
        nout = Y.shape[1]
        self.model = mlp(X.shape[1], args.width, args.depth, nout).to(dev)
        self.dev = dev
        self.nparams = sum(p.numel() for p in self.model.parameters())
        self.muY_t = torch.from_numpy(self.muY.astype(np.float32)).to(dev)
        self.sdY_t = torch.from_numpy(self.sdY.astype(np.float32)).to(dev)
        self.ec_c_t = torch.from_numpy(np.asarray(meta["Ec_c"], np.float32)).to(dev)
        if mode == "logg":
            self.e1t = torch.from_numpy(meta["e1"].astype(np.float32)).to(dev)
            self.e2t = torch.from_numpy(meta["e2"].astype(np.float32)).to(dev)
            self.ept = torch.from_numpy(meta["Ehat_p"].astype(np.float32)).to(dev)
            self.at = torch.from_numpy(meta["a"].astype(np.float32)).to(dev)

    def loss_pred(self, out, idx):
        Yp = out * self.sdY_t + self.muY_t
        if self.mode == "hyper":
            return Yp
        D = torch.stack([Yp[:, 1], Yp[:, 2], Yp[:, 3]], dim=1)
        D = D / torch.clamp(torch.linalg.norm(D, dim=1, keepdim=True), min=1e-30)
        Ehat = (D[:, 0:1] * self.e1t[idx] + D[:, 1:2] * self.e2t[idx]
                + D[:, 2:3] * self.ept[idx])
        mag = torch.exp(torch.clamp(Yp[:, 0:1], -30.0, 30.0)) * self.at[idx].unsqueeze(1)
        return mag * Ehat

    def predict_t(self, idx_t):
        self.model.eval()
        if not torch.is_tensor(idx_t):
            idx_t = torch.as_tensor(np.asarray(idx_t), device=self.dev)
        idx = idx_t.detach().cpu().numpy()
        with torch.no_grad():
            out = self.model(self.Xt[idx_t]).cpu().numpy().astype(np.float64)
        sub = {"mode": self.meta["mode"], "p": self.meta["p"][idx],
               "s": self.meta["s"][idx]}
        if self.mode == "logg":
            sub.update({"e1": self.meta["e1"][idx], "e2": self.meta["e2"][idx],
                        "Ehat_p": self.meta["Ehat_p"][idx], "a": self.meta["a"][idx]})
        return reconstruct(out, sub, self.muY, self.sdY)


def train_one(net, tr_idx, va_idx, d, args):
    dev = net.dev
    opt = torch.optim.AdamW(net.model.parameters(), lr=args.lr, weight_decay=args.wd)
    sched = torch.optim.lr_scheduler.CosineAnnealingLR(opt, T_max=args.epochs)
    tr_t = torch.from_numpy(tr_idx).to(dev)
    best = {"val": 1e30, "epoch": -1, "state": None}
    hist = []
    Ec_all = np.asarray(d["E_conv"], float)
    Ec_t = None
    for ep in range(args.epochs):
        net.model.train()
        perm = tr_t[torch.randperm(len(tr_t), device=dev)]
        tot = 0.0
        for s in range(0, len(perm), args.batch):
            idx = perm[s:s + args.batch]
            out = net.model(net.Xt[idx])
            pred = net.loss_pred(out, idx)
            ref = net.ec_c_t[idx]
            e = (pred - ref) / (1.0 + torch.abs(ref))
            loss = torch.mean(e * e)
            opt.zero_grad(); loss.backward()
            torch.nn.utils.clip_grad_norm_(net.model.parameters(), 1.0); opt.step()
            tot += float(loss) * len(idx)
        sched.step()
        if ep % 25 == 0 or ep == args.epochs - 1:
            pv = net.predict_t(va_idx)
            mv = metrics(pv, d, va_idx)
            hist.append({"epoch": ep, "val_p99": mv["p99"], "val_worst": mv["worst"],
                         "loss": tot / len(tr_idx)})
            if mv["p99"] < best["val"]:
                best = {"val": mv["p99"], "worst": mv["worst"], "epoch": ep,
                        "state": {k: v.detach().clone() for k, v in net.model.state_dict().items()}}
            if ep % 200 == 0:
                print(f"  ep {ep} loss {tot/len(tr_idx):.3e} val_p99 {mv['p99']:.3e} "
                      f"val_worst {mv['worst']:.3e}", flush=True)
    net.model.load_state_dict(best["state"])
    return best, hist


def bench(net, n_slots=200000):
    dev = net.dev
    idx = torch.arange(min(n_slots, len(net.Xt)), device=dev)
    for _ in range(3):
        net.predict_t(idx)
    torch.cuda.synchronize()
    out = {}
    for bs in (10000, 100000):
        b = idx[:bs]
        t0 = time.time()
        rep = 5
        for _ in range(rep):
            net.predict_t(b)
        torch.cuda.synchronize()
        out[str(bs)] = (time.time() - t0) / rep / len(b) * 1e6
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--tag", required=True)
    ap.add_argument("--data", choices=["pilot", "dense"], default="pilot")
    ap.add_argument("--dense-dir", default=os.path.expanduser("~/pr24/t119/dense"))
    ap.add_argument("--dense-rows", type=int, default=0,
                    help="keep only row indices < N in the dense train split")
    ap.add_argument("--mode", choices=["hyper", "logg"], default="hyper")
    ap.add_argument("--specialists", action="store_true")
    ap.add_argument("--eval-dense", default="",
                    help="also evaluate on this dense test npz (common test set)")
    ap.add_argument("--width", type=int, default=512)
    ap.add_argument("--depth", type=int, default=4)
    ap.add_argument("--epochs", type=int, default=1500)
    ap.add_argument("--batch", type=int, default=512)
    ap.add_argument("--lr", type=float, default=1e-3)
    ap.add_argument("--wd", type=float, default=1e-5)
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--gpu", type=int, default=0)
    ap.add_argument("--out", default=os.path.expanduser("~/pr24/t119/runs"))
    ap.add_argument("--bench", action="store_true")
    a = ap.parse_args()
    torch.manual_seed(a.seed); np.random.seed(a.seed)
    dev = torch.device(f"cuda:{a.gpu}")
    os.makedirs(a.out, exist_ok=True)
    d = load_data(a)
    X, meta = features(d, a.mode)
    split = np.asarray(d["split"])
    g = np.asarray(d["gamma"], float)
    trf, va, te = split == "train", split == "val", split == "test"

    eval_sets = {"own_test": (d, np.where(te)[0])}
    if a.eval_dense:
        dd = dict(np.load(a.eval_dense, allow_pickle=True))
        Xd, metad = features(dd, a.mode)
        eval_sets["dense_test"] = (dd, np.arange(len(dd["gamma"])), Xd, metad)

    rep = {"tag": a.tag, "args": vars(a), "n_rows": {k: int(v.sum()) for k, v in
           (("train", trf), ("val", va), ("test", te))}}

    if not a.specialists:
        net = Net(a.mode, X, meta, trf, a, dev)
        rep["n_params"] = net.nparams
        best, hist = train_one(net, np.where(trf)[0], np.where(va)[0], d, a)
        rep["best_epoch"] = best["epoch"]
        rep["train"] = metrics(net.predict_t(np.where(trf)[0]), d, np.where(trf)[0])
        rep["train_strat"] = strat(net.predict_t(np.where(trf)[0]), d, np.where(trf)[0])
        for nm, item in eval_sets.items():
            if len(item) == 2:
                de, sel = item
                pr = net.predict_t(torch.from_numpy(sel).to(dev))
                rep[nm] = metrics(pr, de, sel)
                rep[nm + "_strat"] = strat(pr, de, sel)
            else:
                de, sel, Xd, metad = item
                Xn = ((Xd - net.muX) / net.sdX).astype(np.float32)
                net.model.eval()
                with torch.no_grad():
                    out = net.model(torch.from_numpy(Xn).to(dev)).cpu().numpy().astype(np.float64)
                pr = reconstruct(out, metad, net.muY, net.sdY)
                rep[nm] = metrics(pr, de, sel)
                rep[nm + "_strat"] = strat(pr, de, sel)
        if a.bench:
            rep["bench_us_per_slot"] = bench(net)
    else:
        models = {}
        for (lo, hi), bn in zip(BINS, BIN_NAMES):
            mtr = np.where(trf & (g >= lo) & (g < hi))[0]
            mva = np.where(va & (g >= lo) & (g < hi))[0]
            if len(mtr) < 50 or len(mva) < 10:
                rep[bn] = {"skipped": True, "train_rows": int(len(mtr))}
                print(f"[{bn}] skipped train={len(mtr)} val={len(mva)}", flush=True)
                continue
            print(f"[{bn}] train={len(mtr)} val={len(mva)}", flush=True)
            net = Net(a.mode, X, meta, trf, a, dev)
            best, hist = train_one(net, mtr, mva, d, a)
            models[bn] = net
            rep[bn] = {"n_params": net.nparams, "best_epoch": best["epoch"],
                       "train": metrics(net.predict_t(torch.from_numpy(mtr).to(dev)), d, mtr),
                       "val": metrics(net.predict_t(torch.from_numpy(mva).to(dev)), d, mva)}

        def combined(item):
            de, sel = item[0], item[1]
            gg = np.asarray(de["gamma"], float)[sel]
            pred = np.zeros((len(sel), 3))
            for (lo, hi), bn in zip(BINS, BIN_NAMES):
                m = (gg >= lo) & (gg < hi)
                if not m.any():
                    continue
                if bn not in models:
                    pred[m] = 0.0
                    continue
                net = models[bn]
                if len(item) == 2:
                    pr = net.predict_t(torch.from_numpy(sel[m]).to(dev))
                else:
                    Xd, metad = item[2], item[3]
                    Xn = ((Xd[m] - net.muX) / net.sdX).astype(np.float32)
                    net.model.eval()
                    with torch.no_grad():
                        out = net.model(torch.from_numpy(Xn).to(dev)).cpu().numpy().astype(np.float64)
                    pr = reconstruct(out, metad, net.muY, net.sdY)
                pred[m] = pr
            return pred

        for nm, item in eval_sets.items():
            de, sel = item[0], item[1]
            pr = combined(item)
            rep[nm] = metrics(pr, de, sel)
            rep[nm + "_strat"] = strat(pr, de, sel)
        if a.bench and models:
            rep["bench_us_per_slot"] = bench(list(models.values())[0])

    with open(os.path.join(a.out, f"{a.tag}.json"), "w") as fh:
        json.dump(rep, fh, indent=1)
    print("RESULT", json.dumps({k: rep.get(k) for k in
          ("train", "own_test", "dense_test") if k in rep}), flush=True)
    if "dense_test_strat" in rep:
        print("DENSE_STRAT", json.dumps(rep["dense_test_strat"]), flush=True)


if __name__ == "__main__":
    main()
